    function current() {
        try {
            var stored = window.localStorage.getItem(STORAGE_KEY);
            if (LANGS.indexOf(stored) >= 0) { return stored; }
        } catch (err) { /* ignore */ }
        return FALLBACK;
    }

    function t(key, vars) {
        var pack = DICT[current()] || DICT[FALLBACK];
        var text = pack[key] || DICT[FALLBACK][key] || key;
        if (vars) {
            Object.keys(vars).forEach(function (name) {
                text = text.split('{' + name + '}').join(vars[name] == null ? '' : String(vars[name]));
            });
        }
        return text;
    }

    function apply(root) {
        var scope = root || document;
        document.documentElement.lang = current();
        scope.querySelectorAll('[data-i18n]').forEach(function (node) {
            node.textContent = t(node.getAttribute('data-i18n'));
        });
        scope.querySelectorAll('[data-i18n-placeholder]').forEach(function (node) {
            node.setAttribute('placeholder', t(node.getAttribute('data-i18n-placeholder')));
        });
        scope.querySelectorAll('.lang-btn').forEach(function (button) {
            button.classList.toggle('active', button.getAttribute('data-lang') === current());
        });
    }

    function remember(lang) {
        if (LANGS.indexOf(lang) < 0) { return; }
        try { window.localStorage.setItem(STORAGE_KEY, lang); } catch (err) { /* ignore */ }
        apply(document);
        document.dispatchEvent(new CustomEvent('autoeasm-lang'));
    }

    window.AUTOEASM_I18N = { current: current, t: t, apply: apply, remember: remember, langs: LANGS };
    document.documentElement.lang = current();
    document.addEventListener('DOMContentLoaded', function () {
        apply(document);
        var row = document.getElementById('lang-row');
        if (!row) { return; }
        row.addEventListener('click', function (event) {
            var button = event.target.closest('.lang-btn');
            if (button) { remember(button.getAttribute('data-lang')); }
        });
    });
